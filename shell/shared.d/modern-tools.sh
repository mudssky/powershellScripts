#!/bin/bash
# ======================================================================
# 文件：modern-tools.sh
# 作用：按工具存在性启用现代 CLI，并在缺失时回退系统命令。
# 兼容性：Bash / Zsh；shared.d 双 shell 共用。
# 设计意图：不覆盖语法不兼容的系统命令；zoxide 初始化在 zz-prompt.sh，eza 别名在 aliases.sh。
# ======================================================================

# -- bat ----------------------------------------------------------------
if command -v bat >/dev/null 2>&1; then
  alias cat='bat'
  # 为脚本和管道场景提供不带装饰的纯文本入口。
  alias catp='bat -pp'
fi

# -- lazygit ------------------------------------------------------------
if command -v lazygit >/dev/null 2>&1; then
  alias lg='lazygit'
fi

